def _gc_miles(a: str, b: str) -> int | None:
    if a not in COORDS or b not in COORDS:
        return None
    la1, lo1 = map(math.radians, COORDS[a])
    la2, lo2 = map(math.radians, COORDS[b])
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    km = 6371.0 * 2 * math.asin(math.sqrt(h))
    return int(round(km * 0.621371 * 1.03))


def route_miles(a: str, b: str) -> tuple[int, bool]:
    """(miles, is_estimate)"""
    if (a, b) in OFFICIAL:
        return OFFICIAL[(a, b)], False
    est = _gc_miles(a, b)
    return (est if est is not None else 300), True
